"""Generate the human-readable forensic report from measured inspection results.

Every number in the output is computed from the :class:`InspectionResult`
rather than transcribed by hand, so the report cannot drift away from the
dataset it describes. Narrative sections state provenance explicitly and keep
verified facts, inferences, and unknowns separated.
"""

from __future__ import annotations

import statistics
from collections import Counter, defaultdict
from pathlib import Path
from typing import TYPE_CHECKING

from idr.dataset.inventory import classify_family as classify_family_of
from idr.dataset.report import select_representative_sessions
from idr.dataset.timestamps import SAMPLING_THRESHOLDS
from idr.version import __version__

if TYPE_CHECKING:
    from idr.dataset.inspect import InspectionResult


def _fmt(value: float | None, digits: int = 4, suffix: str = "") -> str:
    if value is None:
        return "n/a"
    return f"{value:.{digits}f}{suffix}"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    if not rows:
        return "_No rows._\n"
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(lines) + "\n"


def _stream_of(result: InspectionResult, relative_path: str) -> str:
    name = Path(relative_path).name.upper()
    if name.startswith("S-"):
        return "smartphone"
    if name.startswith("V-"):
        return "vehicle"
    return "unknown"


def generate_forensic_report(
    result: InspectionResult, output: Path, plot_paths: list[Path]
) -> Path:
    """Write ``IO_VNBD_Forensic_Report.md`` describing the scanned dataset."""
    files = [f for f in result.files if f.is_file]
    csv_files = [f for f in files if f.extension == ".csv"]
    pointers = [f for f in files if f.is_lfs_pointer]

    phone_scans = {p: s for p, s in result.scans.items() if _stream_of(result, p) == "smartphone"}
    vehicle_scans = {p: s for p, s in result.scans.items() if _stream_of(result, p) == "vehicle"}

    phone_ts = [t for t in result.timestamps if _stream_of(result, t.relative_path) == "smartphone"]
    vehicle_ts = [t for t in result.timestamps if _stream_of(result, t.relative_path) == "vehicle"]

    def rate_summary(reports: list) -> str:
        rates = [t.estimated_rate_hz for t in reports if t.estimated_rate_hz]
        if not rates:
            return "no measurable rate"
        return (
            f"median {statistics.median(rates):.4f} Hz "
            f"(min {min(rates):.4f}, max {max(rates):.4f}, n={len(rates)})"
        )

    def rate_bucket(rate: float | None) -> str:
        """Group a measured rate into the families actually present."""
        if rate is None:
            return "unknown"
        for low, high, label in (
            (0.0, 3.0, "~2 Hz"),
            (3.0, 15.0, "~10 Hz"),
            (15.0, 40.0, "~24 Hz"),
            (40.0, 5000.0, "~1000 Hz"),
        ):
            if low <= rate < high:
                return label
        return "other"

    schema_groups: dict[str, list[str]] = defaultdict(list)
    for path, schema in result.schemas.items():
        schema_groups[schema.schema_id].append(path)

    total_rows = sum(s.row_count for s in result.scans.values())
    durations = [t.duration_s for t in result.timestamps if t.duration_s]
    total_duration_h = sum(durations) / 3600.0 if durations else 0.0
    phone_duration_h = (
        sum(t.duration_s for t in phone_ts if t.duration_s) / 3600.0 if phone_ts else 0.0
    )
    vehicle_duration_h = (
        sum(t.duration_s for t in vehicle_ts if t.duration_s) / 3600.0 if vehicle_ts else 0.0
    )

    sampling_classes = Counter(t.sampling_class for t in result.timestamps)
    families = Counter(f.dataset_family for f in files)
    paired = [s for s in result.sessions if s.is_paired]

    sync_kinds = Counter(s.interpretation for s in result.synchronization)
    outage_total = sum(o.outage_count for o in result.outage_reports)
    zero_gnss = [o for o in result.outage_reports if o.availability_fraction == 0.0]
    full_gnss = [o for o in result.outage_reports if o.availability_fraction >= 0.999]

    encodings = Counter(s.encoding for s in result.schemas.values())
    non_utf8 = [p for p, s in result.schemas.items() if not s.encoding_is_utf8]

    findings_by_kind = Counter(f.interpretation for f in result.range_findings)
    unknown_roles = {
        column.raw_name.strip()
        for schema in result.schemas.values()
        for column in schema.columns
        if column.semantic_role == "unknown"
    }

    selections = select_representative_sessions(result)

    lines: list[str] = []
    add = lines.append

    add("# IO-VNBD Forensic Analysis\n")
    add(
        f"_Generated by `idr {__version__}` Phase 1 dataset inspection on "
        f"{result.scan_timestamp} from `{result.dataset_path}`._\n"
    )
    add(
        "Every statistic below is computed from the actual files scanned in this "
        "run. Claims are tagged with their provenance: **VERIFIED_FROM_FILE**, "
        "**VERIFIED_FROM_DATASET_DOCUMENTATION**, **VERIFIED_FROM_OFFICIAL_SOURCE**, "
        "**INFERRED**, or **UNVERIFIED**.\n"
    )

    # 1 ---------------------------------------------------------------
    redundant = sum(len(paths) - 1 for paths in result.duplicate_groups.values())
    canonical_duration_h = (
        sum(
            t.duration_s
            for t in result.timestamps
            if t.duration_s and t.relative_path in result.canonical_files
        )
        / 3600.0
    )

    add("## 1. Executive Summary\n")
    add(
        f"- **{len(csv_files)} CSV data files** across **{len(result.sessions)} sessions**, "
        f"**{len(paired)} of them paired** smartphone/vehicle recordings.\n"
        f"- **Only {len(result.canonical_files)} of those {len(csv_files)} files hold distinct "
        f"content**: {len(result.duplicate_groups)} duplicate group(s) account for "
        f"**{redundant} byte-identical redundant copies** — a train/test leakage hazard, see "
        f"§6a.\n"
        f"- **{total_rows:,} data rows** scanned, spanning **{total_duration_h:.1f} hours** of "
        f"file time ({phone_duration_h:.1f} h smartphone, {vehicle_duration_h:.1f} h vehicle), "
        f"falling to **{canonical_duration_h:.1f} h once duplicates are excluded**. Note this "
        f"still exceeds the ~98 h implied by the dataset README's own headline figures; the "
        f"discrepancy is **UNVERIFIED** and is discussed in §9.\n"
        f"- **{len(schema_groups)} distinct schema variants** detected.\n"
        f"- Sampling is overwhelmingly regular: "
        f"{sampling_classes.get('stable', 0)} stream(s) classified `stable`, "
        f"{sampling_classes.get('mostly_stable', 0)} `mostly_stable`, "
        f"{sampling_classes.get('irregular', 0)} `irregular`, "
        f"{sampling_classes.get('severely_irregular', 0)} `severely_irregular`.\n"
        f"- Smartphone measured rate: {rate_summary(phone_ts)}. "
        f"Vehicle measured rate: {rate_summary(vehicle_ts)}.\n"
        f"- **There is no GNSS outage anywhere in this dataset**: {outage_total} loss-of-fix "
        f"gap(s) were found across all {len(result.outage_reports)} streams, every one of "
        f"which reports a valid fix on 100% of its rows. No file annotates an outage either. "
        f"**A project about surviving GNSS outages therefore has no real outages to learn "
        f"from — Phase 2 must synthesize them and label them as synthetic.**\n"
        f"- Offsetting that: the **smartphone GNSS position is forward-filled at ~0.1 Hz**, so "
        f"a '100% availability' stream is really a sparse position source (§11).\n"
    )
    add(
        "> **Most important caveat for Phase 2:** the copy of IO-VNBD originally "
        "present in this repository contained *no data at all* — all 564 CSVs and "
        "161 JPGs were unresolved Git LFS pointers. The real content was acquired "
        "from the official upstream repository and SHA-256 verified. See §2 and §3.\n"
    )

    # 2 ---------------------------------------------------------------
    add("## 2. Dataset Source & Acquisition\n")
    add(
        "IO-VNBD (Inertial Odometry Vehicle Navigation Benchmark Dataset) is a public "
        "benchmark recorded with a research vehicle on public roads in the United "
        "Kingdom, Nigeria and France. Per the README shipped inside the dataset "
        "(**VERIFIED_FROM_DATASET_DOCUMENTATION**):\n\n"
        "- sensors include a GPS receiver, inertial sensors and wheel-speed sensors on the "
        "vehicle, plus the inertial sensors and GPS receiver of an Android smartphone "
        "**sampling at 10 Hz**;\n"
        "- approximately **40 hours over 1,300 km** of vehicle-extracted data and "
        "**58 hours over 4,400 km** of smartphone-recorded data;\n"
        "- scenarios include traffic, roundabouts and hard braking across country roads "
        "and motorways.\n\n"
        "The local tree `data/IO-VNBD_dataset/IO-VNBD-master/` is a ZIP export of the "
        "upstream GitHub repository, which is why it carried only LFS pointer stubs. "
        "Actual objects were fetched via the Git LFS batch API of the official upstream "
        "repository `https://github.com/onyekpeu/IO-VNBD.git` "
        "(**VERIFIED_FROM_OFFICIAL_SOURCE**). Because an LFS `oid` *is* the SHA-256 of "
        "the content, every one of the 564 downloaded objects was hash-verified before "
        "being written. See `data/metadata/io_vnbd/acquisition_manifest.csv`.\n\n"
        "The original pointer tree was left byte-for-byte untouched and remains the "
        "provenance record; content was materialized into a separate directory.\n"
    )

    # 3 ---------------------------------------------------------------
    add("## 3. Local Dataset Integrity\n")
    add(
        f"- Files scanned: **{len(files)}** ({len(csv_files)} CSV).\n"
        f"- Unresolved LFS pointers in the scanned tree: **{len(pointers)}**.\n"
        f"- Unreadable files: **{len(result.unreadable_files)}**.\n"
        f"- CSV parse failures: **{len(result.parse_failures)}**.\n"
        f"- Distinct schema variants: **{len(schema_groups)}**.\n"
    )
    if result.parse_failures:
        add("\nParse failures:\n")
        for failure in result.parse_failures[:20]:
            add(f"- `{failure}`\n")
    add(
        "\n**Character encoding is not uniform** (**VERIFIED_FROM_FILE**): "
        + ", ".join(f"`{enc}` × {count}" for enc, count in sorted(encodings.items()))
        + f". {len(non_utf8)} file(s) are not valid UTF-8 and require a cp1252 fallback. "
        "Smartphone headers mix raw cp1252 bytes (`m/s²`) with double-encoded UTF-8 "
        "sequences (`Â°`, `Î¼T`) in the *same* header line. Phase 2 must not assume UTF-8.\n"
    )
    add(
        "\n**Missing-file detection is not possible.** The dataset publishes no manifest "
        "of expected files, so an absent session cannot be distinguished from one that "
        "never existed (**UNVERIFIED**).\n"
    )

    # 4 ---------------------------------------------------------------
    add("## 4. Repository / File Structure\n")
    add(
        "```text\n"
        "IO-VNBD-master/\n"
        "├── README.md, README_1.pdf, Data Checker Table 2.py   (documentation)\n"
        "├── Synchronised V abd S datasets/\n"
        "│   ├── Categorised IOVNB Dataset/<Label> (Driver X)/<Session>/{S,V}-<id>.csv\n"
        "│   └── Uncategorised IOVNB Dataset/{S,V}-Dataset/\n"
        "└── Unsynchronised V and S Dataset/\n"
        "    ├── Categorised IOVNB (V) Dataset/V Dataset/\n"
        "    └── Uncategorised IOVNB (V and S) Dataset/{S,V}-Dataset/\n"
        "```\n\n"
        "Note the upstream directory names contain typos (`abd`, `fof`) and inconsistent "
        "capitalization (`S-Vta11.csv` pairs with `V-vta11.csv`). Phase 2 must match "
        "session ids case-insensitively.\n"
    )

    # 5 ---------------------------------------------------------------
    add("## 5. Dataset Families\n")
    add(
        _table(
            ["Family", "Files"],
            [[f"`{family}`", str(count)] for family, count in sorted(families.items())],
        )
    )

    # 6 ---------------------------------------------------------------
    add("## 6. Session Inventory\n")
    add(
        f"**{len(result.sessions)} sessions** discovered, **{len(paired)} paired** "
        f"(both an `S-` and a `V-` file share a session id).\n\n"
        "Pairing is **INFERRED** from the filename convention. Driver letters are "
        "**VERIFIED_FROM_FILE** where a `X (Driver Y)` directory exists. "
        "**Country of recording is UNVERIFIED** — the dataset spans the UK, Nigeria and "
        "France, but nothing in the file tree says which session was recorded where.\n\n"
        "Full listing: `data/metadata/io_vnbd/session_inventory.csv`.\n"
    )
    by_family_sessions = Counter(s.dataset_family for s in result.sessions)
    add(
        _table(
            ["Family", "Sessions", "Paired"],
            [
                [
                    f"`{family}`",
                    str(count),
                    str(sum(1 for s in paired if s.dataset_family == family)),
                ]
                for family, count in sorted(by_family_sessions.items())
            ],
        )
    )

    # 6a --------------------------------------------------------------
    add("\n## 6a. Duplicate Content (train/test leakage hazard)\n")
    if not result.duplicate_groups:
        add("_No duplicated file content was found._\n")
    else:
        spread: Counter[tuple[str, ...]] = Counter()
        for paths in result.duplicate_groups.values():
            spread[tuple(sorted({classify_family_of(path) for path in paths}))] += 1
        add(
            f"**{len(csv_files)} CSV files contain only {len(result.canonical_files)} distinct "
            f"contents.** {len(result.duplicate_groups)} SHA-256 group(s) have more than one "
            f"copy, totalling **{redundant} redundant file(s)** "
            f"(**VERIFIED_FROM_FILE** — full-file hashes, not samples).\n\n"
            "IO-VNBD publishes the same recordings in more than one place: a session can appear "
            "in both the categorized and the uncategorized tree, and across the synchronized and "
            "unsynchronized trees. The copies are byte-identical, not re-recordings.\n\n"
            "**This is the single biggest correctness trap for Phase 2.** A naive file-level "
            "train/test split would place byte-identical data on both sides, producing "
            "meaningless validation scores — a direct violation of Rule 9 (no information "
            "leakage). Phase 2 must split on *content hash* or on canonical session identity, "
            "never on file path.\n\n"
            "Where duplicate copies live (by family combination):\n\n"
        )
        add(
            _table(
                ["Families sharing identical content", "Groups"],
                [
                    [" + ".join(f"`{f}`" for f in families), str(count)]
                    for families, count in sorted(spread.items(), key=lambda kv: -kv[1])
                ],
            )
        )
        add(
            "\nEvery copy is listed in `duplicate_files.csv`, with `is_canonical` marking the "
            "one representative per distinct content that de-duplicated totals use.\n"
        )

    # 7 / 8 -----------------------------------------------------------
    for title, scans, filename in (
        ("7. Smartphone Schema", phone_scans, "smartphone_schema.json"),
        ("8. Vehicle / Reference Schema", vehicle_scans, "vehicle_schema.json"),
    ):
        add(f"## {title}\n")
        variants: dict[str, list[str]] = defaultdict(list)
        for path in scans:
            if path in result.schemas:
                variants[result.schemas[path].schema_id].append(path)
        if not variants:
            add("_No files of this stream were scanned._\n")
            continue
        add(f"**{len(variants)} schema variant(s)**; details in `{filename}`.\n\n")
        for schema_id, paths in sorted(variants.items(), key=lambda kv: -len(kv[1])):
            example = result.schemas[paths[0]]
            add(
                f"### Variant `{schema_id}` — {len(paths)} file(s), "
                f"{example.column_count} columns, encoding `{example.encoding}`\n\n"
            )
            add(
                _table(
                    ["#", "Column", "Unit", "Semantic role", "Evidence"],
                    [
                        [
                            str(column.index),
                            f"`{column.normalized_name}`",
                            column.unit or "—",
                            f"`{column.semantic_role}`",
                            column.role_evidence,
                        ]
                        for column in example.columns
                    ],
                )
            )
            add("\n")

    if unknown_roles:
        add(
            "**Columns with no recognized semantic role (UNVERIFIED):** "
            + ", ".join(f"`{name}`" for name in sorted(unknown_roles))
            + "\n"
        )
    else:
        add(
            "**Every column in every scanned schema mapped to a recognized semantic "
            "role** — there are no unidentified fields (**VERIFIED_FROM_FILE**).\n"
        )

    # 9 ---------------------------------------------------------------
    add("\n## 9. Timestamp & Sampling Analysis\n")
    add(
        "Rates below are **measured**, not assumed. The rate is derived from the *median* "
        "inter-sample interval so that occasional large gaps do not understate cadence.\n\n"
        f"- Smartphone: {rate_summary(phone_ts)}\n"
        f"- Vehicle: {rate_summary(vehicle_ts)}\n\n"
        "The **median** matches the 10 Hz nominal rate stated in the dataset README, so the "
        "documented rate is corroborated rather than taken on trust — **but the median hides "
        "real heterogeneity.** The dataset is not uniformly 10 Hz:\n\n"
    )
    rate_rows: list[list[str]] = []
    buckets: dict[tuple[str, str], int] = {}
    for report_ts in result.timestamps:
        stream = _stream_of(result, report_ts.relative_path)
        buckets[(stream, rate_bucket(report_ts.estimated_rate_hz))] = (
            buckets.get((stream, rate_bucket(report_ts.estimated_rate_hz)), 0) + 1
        )
    for (stream, label), count in sorted(buckets.items()):
        rate_rows.append([stream, label, str(count)])
    add(_table(["Stream", "Measured rate family", "Streams"], rate_rows))
    add(
        "\n**The vehicle stream is uniformly ~10 Hz. The smartphone stream is not**: alongside "
        "the ~10 Hz majority there are distinct families recorded at roughly 2 Hz, ~24 Hz and "
        "~1000 Hz (1 ms sampling). Phase 2 must read the measured rate per file from "
        "`sampling_report.csv` rather than assuming 10 Hz, and must decide explicitly how to "
        "handle the non-10 Hz files (resample, or exclude with justification).\n\n"
        "Stability thresholds (coefficient of variation of the interval):\n\n"
    )
    add(
        _table(
            ["Class", "Rule", "Streams"],
            [
                [f"`{name}`", f"`{rule}`", str(sampling_classes.get(name, 0))]
                for name, rule in SAMPLING_THRESHOLDS.items()
            ],
        )
    )
    non_monotonic = [t for t in result.timestamps if not t.is_monotonic and t.valid_timestamps]
    duplicated = [t for t in result.timestamps if t.duplicate_timestamp_count]
    misaligned = [t for t in result.timestamps if t.suspected_column_misalignment]
    if misaligned:
        add(
            f"\n### Column misalignment — {len(misaligned)} file(s)\n\n"
            "In these files **not one value in the timestamp column parses as a number**, "
            "despite the file having many rows. Inspection confirms the cause: an extra "
            "empty field early in each data row shifts every subsequent value one column to "
            "the right relative to the header, so the header label on every channel past that "
            "point is wrong (**VERIFIED_FROM_FILE**).\n\n"
            "This is silent corruption — the file parses cleanly and only the *values* are "
            "mislabelled. **Phase 2 must either repair the shift explicitly or exclude these "
            "files**; reading them by column name yields wrong data with no error.\n\n"
        )
        add(
            _table(
                ["File", "Rows", "Detail"],
                [
                    [f"`{Path(t.relative_path).name}`", f"{t.missing_timestamps:,}", t.note]
                    for t in misaligned
                ],
            )
        )

    # Report one row per distinct file: duplicate copies would otherwise repeat.
    seen_names: set[str] = set()
    discontinuous = []
    for report_ts in result.timestamps:
        if report_ts.coefficient_of_variation is None or report_ts.coefficient_of_variation <= 5.0:
            continue
        name = Path(report_ts.relative_path).name
        if name in seen_names:
            continue
        seen_names.add(name)
        discontinuous.append(report_ts)
    if discontinuous:
        add(
            f"\n**{len(discontinuous)} stream(s) have a coefficient of variation above 5** while "
            "still showing a 0.1 s median interval — i.e. mostly-regular 10 Hz data interrupted "
            "by a few very large jumps. That pattern is consistent with several separate trips "
            "concatenated into one file. Phase 2 should segment such files on the large gaps "
            "rather than treating them as one continuous trajectory "
            "(**VERIFIED_FROM_FILE** that the jumps exist; **INFERRED** that they are trip "
            "boundaries):\n\n"
        )
        add(
            _table(
                ["Stream file", "Median Δt (s)", "Max Δt (s)", "CV"],
                [
                    [
                        f"`{Path(t.relative_path).name}`",
                        _fmt(t.delta_median_s, 3),
                        _fmt(t.delta_max_s, 1),
                        _fmt(t.coefficient_of_variation, 1),
                    ]
                    for t in sorted(
                        discontinuous,
                        key=lambda r: -(r.coefficient_of_variation or 0.0),
                    )[:12]
                ],
            )
        )
    add(
        f"\n**Duration does not reconcile with the dataset's headline figures.** Measured file "
        f"time totals {total_duration_h:.1f} h ({canonical_duration_h:.1f} h de-duplicated), "
        f"against the README's ~40 h vehicle + ~58 h smartphone ≈ 98 h. The gap is "
        f"**UNVERIFIED**: plausible explanations include the published figures covering only a "
        f"subset of sessions, excluding stationary periods, or counting driving time rather "
        f"than logged time. Duration here is computed as last-minus-first timestamp per file, "
        f"which for the concatenated files noted above also spans the inter-trip gaps. Phase 2 "
        f"should not treat either number as authoritative without resolving this.\n"
        f"\n- Streams with non-monotonic timestamps: **{len(non_monotonic)}**\n"
        f"- Streams with duplicate timestamps: **{len(duplicated)}**\n"
        f"- Streams with no usable timestamp column: "
        f"**{sampling_classes.get('unknown', 0)}**\n\n"
        "Per-stream detail: `timestamp_report.csv`, `sampling_report.csv`.\n"
    )
    add(
        "\n**Two different clocks exist and they are not interchangeable "
        "(VERIFIED_FROM_FILE):**\n\n"
        "- Smartphone files carry `TIME SINCE START (ms)` — elapsed milliseconds from the "
        "start of recording — plus a `DATE` string in the non-standard format "
        "`YYYY-MM-DD HH:MM:SS:mmm` (milliseconds after a **colon**, which no standard "
        "datetime parser accepts).\n"
        "- Vehicle files carry `Time Since Start of Day (seconds)`, an absolute "
        "within-day clock with no date component.\n\n"
        "Neither stream carries a timezone-qualified absolute timestamp.\n"
    )

    # 10 --------------------------------------------------------------
    add("\n## 10. Synchronization Analysis\n")
    if not result.synchronization:
        add("_No paired sessions were available to analyze._\n")
    else:
        add(
            f"**{len(result.synchronization)} paired session(s) analyzed.** Both streams "
            "were placed on a seconds-since-local-midnight axis (the vehicle provides one "
            "directly; the smartphone's `DATE` column was parsed into one).\n\n"
        )
        add(
            _table(
                ["Interpretation", "Sessions"],
                [[f"`{kind}`", str(count)] for kind, count in sorted(sync_kinds.items())],
            )
        )
        offsets = [s.mean_offset_s for s in result.synchronization if s.mean_offset_s is not None]
        hour_offsets = Counter(
            s.whole_hour_offset for s in result.synchronization if s.whole_hour_offset is not None
        )
        residuals = [
            abs(s.residual_offset_s)
            for s in result.synchronization
            if s.residual_offset_s is not None
        ]
        matching_rows = sum(1 for s in result.synchronization if s.row_counts_match)
        aligned_hours = hour_offsets.get(0, 0)
        shifted_hours = sum(count for hours, count in hour_offsets.items() if hours)
        near_whole_hour = sum(
            1 for value in offsets if abs(value - round(value / 3600.0) * 3600.0) <= 60.0
        )
        add(
            f"\n- **Most pairs are already closely aligned**: {aligned_hours} of "
            f"{len(result.synchronization)} have a whole-hour offset of 0, with a median "
            f"absolute sub-hour residual of "
            f"{_fmt(statistics.median(residuals) if residuals else None, 2, ' s')}.\n"
            f"- **A minority are shifted by a whole hour**: {shifted_hours} pair(s). "
            f"Full distribution (hours → pairs): {dict(sorted(hour_offsets.items()))}.\n"
            f"- Median offset across pairs: "
            f"{_fmt(statistics.median(offsets) if offsets else None, 2, ' s')} "
            f"(min {_fmt(min(offsets) if offsets else None, 1, ' s')}, "
            f"max {_fmt(max(offsets) if offsets else None, 1, ' s')}).\n"
            f"- Offsets within 60 s of a whole-hour multiple (0 h included): "
            f"**{near_whole_hour}/{len(offsets)}**.\n"
            f"- Pairs whose smartphone and vehicle row counts are identical: "
            f"**{matching_rows}/{len(result.synchronization)}**.\n\n"
            f"**INFERRED interpretation:** for the {shifted_hours} pair(s) offset by ~1 h, the "
            "shift is consistent with one stream logging local time (BST) and the other UTC "
            "rather than a clock fault. That is an inference — *the dataset documents no "
            "reference synchronization*, so there is nothing to verify it against, and it must "
            "not be generalized to the majority of pairs, which show no such shift.\n\n"
            "**Offset must be measured per pair, never assumed.** Phase 1 deliberately does "
            "**not** correct any stream.\n\n"
            "Per-pair detail including drift in ppm: `synchronization_report.csv`.\n"
        )

    # 11 --------------------------------------------------------------
    add("\n## 11. GNSS Availability & Outages\n")
    add(
        "**No file anywhere in IO-VNBD annotates GNSS outages** — there is no outage "
        "metadata, marker column, or accompanying documentation of induced dropouts "
        "(**VERIFIED_FROM_FILE**: the full file inventory contains only CSVs, JPGs and "
        "three documentation files). Consequently:\n\n"
        "- every interval in `gnss_outages.csv` has `source = observed_missingness`;\n"
        "- **none** is labelled `documented`;\n"
        "- confidence is recorded as `observed_high` — the *absence of a fix* is measured "
        "with certainty, but the *cause* (tunnel, urban canyon, logger fault) is "
        "**UNVERIFIED**.\n\n"
        f"- Streams with a GNSS field: "
        f"**{sum(1 for o in result.outage_reports if o.has_gnss_fields)}"
        f"/{len(result.outage_reports)}**\n"
        f"- Streams with ≥99.9% availability: **{len(full_gnss)}**\n"
        f"- Streams with 0% availability: **{len(zero_gnss)}**\n"
        f"- Total observed gap intervals (≥1.0 s): **{outage_total}**\n\n"
        "A fix is counted as valid when latitude and longitude are both present, finite, "
        "and not exactly (0, 0) — the classic 'no fix' sentinel.\n"
    )

    # Position staleness — the single most consequential GNSS finding.
    phone_rates = [
        o.position_update_rate_hz
        for o in result.outage_reports
        if o.stream == "smartphone" and o.position_update_rate_hz
    ]
    vehicle_rates = [
        o.position_update_rate_hz
        for o in result.outage_reports
        if o.stream == "vehicle" and o.position_update_rate_hz
    ]
    phone_medians = [
        o.median_update_interval_s
        for o in result.outage_reports
        if o.stream == "smartphone" and o.median_update_interval_s
    ]
    vehicle_medians = [
        o.median_update_interval_s
        for o in result.outage_reports
        if o.stream == "vehicle" and o.median_update_interval_s
    ]
    holds = [i for i in result.outage_intervals if i.source == "observed_position_hold"]

    add(
        "\n### GNSS position staleness — a 100% fix rate is NOT a 10 Hz position source\n\n"
        "Availability counts rows that *carry* a position. It does not ask whether that "
        "position is **new**. Measuring how often latitude/longitude actually *change* "
        "gives a very different picture (**VERIFIED_FROM_FILE**):\n\n"
    )
    add(
        _table(
            ["Stream", "Median position-update rate", "Median update interval", "Streams"],
            [
                [
                    "smartphone",
                    f"{statistics.median(phone_rates):.4f} Hz" if phone_rates else "n/a",
                    f"{statistics.median(phone_medians):.2f} s" if phone_medians else "n/a",
                    str(len(phone_rates)),
                ],
                [
                    "vehicle",
                    f"{statistics.median(vehicle_rates):.4f} Hz" if vehicle_rates else "n/a",
                    f"{statistics.median(vehicle_medians):.2f} s" if vehicle_medians else "n/a",
                    str(len(vehicle_rates)),
                ],
            ],
        )
    )
    add(
        "\n**The smartphone GNSS position is forward-filled between updates that arrive "
        "roughly two orders of magnitude more slowly than the 10 Hz row rate.** The vehicle "
        "reference position, by contrast, genuinely refreshes at ~10 Hz. Consequences for "
        "Phase 2:\n\n"
        "- consecutive smartphone GPS rows are overwhelmingly duplicates, so treating them "
        "as independent 10 Hz fixes would massively overstate the GNSS information available;\n"
        "- the **vehicle stream is the high-rate position reference**, not the smartphone;\n"
        "- a smartphone-only navigation solution is effectively dead-reckoning between "
        "sparse position updates even when a 'fix' is present on every row.\n\n"
        f"Held-position spans of at least {30:.0f} s were recorded as intervals in "
        f"`gnss_outages.csv` with `source = observed_position_hold`: **{len(holds)}** such "
        "span(s) were found. These are the closest thing in IO-VNBD to a GNSS outage, but "
        "they are **staleness, not loss of fix**, and are labelled accordingly.\n"
    )
    worst = sorted(result.outage_reports, key=lambda o: -o.total_outage_s)[:10]
    if worst and worst[0].total_outage_s > 0:
        add("\nLargest observed GNSS gaps:\n\n")
        add(
            _table(
                ["Stream file", "Gaps", "Total (s)", "Longest (s)", "Availability"],
                [
                    [
                        f"`{Path(o.relative_path).name}`",
                        str(o.outage_count),
                        f"{o.total_outage_s:.1f}",
                        f"{o.longest_outage_s:.1f}",
                        f"{100 * o.availability_fraction:.2f}%",
                    ]
                    for o in worst
                    if o.total_outage_s > 0
                ],
            )
        )

    # 12 --------------------------------------------------------------
    add("\n## 12. Scenario Inventory\n")
    categories = Counter(s.category for s in result.sessions if s.category)
    add(
        "Scenario labels are taken **only** from directory names that actually exist "
        "(`<Label> (Driver X)`); no categories were invented. Sessions outside a "
        "categorized directory are recorded as `uncategorized` rather than assigned a "
        "guessed label.\n\n"
    )
    add(
        _table(
            ["Category label", "Sessions", "Evidence"],
            [
                [f"`{name}`", str(count), "VERIFIED_FROM_FILE"]
                for name, count in sorted(categories.items())
            ]
            + [
                [
                    "`uncategorized`",
                    str(sum(1 for s in result.sessions if not s.category)),
                    "UNVERIFIED",
                ]
            ],
        )
    )
    add(
        "\nThe meaning of each label (e.g. `Vta`, `Vtb`, `Vw`, `Vf`) is **UNVERIFIED** — "
        "the dataset does not define these abbreviations in any shipped documentation. "
        "Full listing: `scenario_inventory.csv`.\n"
    )

    # 13 --------------------------------------------------------------
    add("\n## 13. Missing Data\n")
    worst_missing = sorted(result.missingness, key=lambda m: -m.missing_percentage)[:15]
    add(
        "Missing values and *present-but-unparseable* values are counted separately, "
        "because they are different problems.\n\n"
    )
    add(
        _table(
            ["File", "Column", "Rows", "Missing", "Missing %", "Non-numeric"],
            [
                [
                    f"`{Path(m.relative_path).name}`",
                    f"`{m.column}`",
                    f"{m.total_rows:,}",
                    f"{m.missing_rows:,}",
                    f"{m.missing_percentage:.3f}%",
                    f"{m.non_numeric_rows:,}",
                ]
                for m in worst_missing
                if m.missing_percentage > 0
            ],
        )
    )
    satellite_records = [
        m for m in result.missingness if m.semantic_role == "gnss_satellites" and m.non_numeric_rows
    ]
    if satellite_records:
        add(
            f"\n**`GPS SATELLITES IN RANGE` is not numeric** in smartphone files "
            f"({len(satellite_records)} file(s) affected): values take the literal form "
            '`"27 / 28"` (in-use / in-view). Any Phase 2 code that calls '
            "`float()` on this column will fail (**VERIFIED_FROM_FILE**).\n"
        )
    add("\nFull detail: `missingness_report.csv`.\n")

    # 14 --------------------------------------------------------------
    add("\n## 14. Data-Range / Anomaly Findings\n")
    add(
        "Values outside a physical plausibility screen are **reported, never removed or "
        "modified**, and each is classified rather than condemned — hard braking, "
        "potholes and aggressive cornering all produce genuine high-amplitude readings.\n\n"
    )
    add(
        _table(
            ["Classification", "Findings"],
            [[f"`{kind}`", str(count)] for kind, count in sorted(findings_by_kind.items())],
        )
    )
    add(
        f"\nTotal findings: **{len(result.range_findings)}** across "
        f"{len({f.relative_path for f in result.range_findings})} file(s). "
        "Full detail with observed min/max per column: `range_findings.csv`.\n"
    )

    # 15 --------------------------------------------------------------
    add("\n## 15. Session Quality\n")
    add(
        "`session_quality.csv` records, per stream: `schema_valid`, `timestamp_quality`, "
        "`missingness_score`, `sampling_quality`, `gnss_availability`, `sampling_class`, "
        "`measured_rate_hz`, `range_finding_count` and `parse_error`.\n\n"
        "A `quality_score` is provided as the **plain mean of the four sub-scores**, each "
        "in [0, 1]. The formula is stored in the CSV alongside every row, and all "
        "underlying metrics are preserved. **The score is a ranking aid only — it is "
        "never used to filter or drop a session**, and Phase 2 should make exclusion "
        "decisions from the underlying metrics, not the aggregate.\n\n"
    )
    if result.quality:
        scores = [q.quality_score for q in result.quality]
        add(
            f"- Streams profiled: **{len(result.quality)}**\n"
            f"- Score range: {min(scores):.3f} – {max(scores):.3f} "
            f"(median {statistics.median(scores):.3f})\n"
        )

    # 16 --------------------------------------------------------------
    add("\n## 16. Representative Sessions\n")
    if selections:
        add(
            "Selected from measured evidence, each with the reason it was chosen. "
            "Categories the dataset does not actually contain are simply absent — none "
            "were forced.\n\n"
        )
        add(
            _table(
                ["Category", "Session", "File", "Why selected"],
                [
                    [
                        f"`{s.category}`",
                        s.session_id,
                        f"`{Path(s.relative_path).name}`",
                        s.reason,
                    ]
                    for s in selections
                ],
            )
        )
    else:
        add("_No sessions could be selected._\n")

    # 17 --------------------------------------------------------------
    add("\n## 17. Diagnostic Plots\n")
    if plot_paths:
        add("Generated under `reports/io_vnbd/plots/`:\n\n")
        for plot in sorted(plot_paths):
            add(f"- `{plot.name}`\n")
    else:
        add("_No plots were generated._\n")

    # 18 --------------------------------------------------------------
    add("\n## 18. Verified Facts vs Inferences vs Unknowns\n")
    add("### Verified from file\n")
    add(
        f"- {len(csv_files)} CSV files, {len(result.sessions)} sessions, "
        f"{len(schema_groups)} schema variants, {total_rows:,} rows.\n"
        "- Exact column names, units, order and dtypes of every schema variant.\n"
        f"- Measured sampling rates ({rate_summary(phone_ts)} smartphone; "
        f"{rate_summary(vehicle_ts)} vehicle).\n"
        "- Per-column missingness and observed numeric ranges.\n"
        "- GNSS fix availability per row and the resulting gap intervals.\n"
        "- Mixed/invalid character encoding in smartphone files.\n"
        '- `GPS SATELLITES IN RANGE` holds non-numeric `"a / b"` strings.\n'
        "- Every acquired object matched the SHA-256 recorded in its LFS pointer.\n"
    )
    add("\n### Verified from dataset documentation\n")
    add(
        "- Recording countries (UK, Nigeria, France), nominal 10 Hz smartphone rate, and "
        "the headline ~40 h/1,300 km vehicle and ~58 h/4,400 km smartphone totals, from "
        "the dataset's own `README.md`.\n"
    )
    add("\n### Inferred\n")
    add(
        "- S/V pairing (from the filename convention, not a declared mapping).\n"
        "- The ~1 h S↔V clock offset seen on a minority of pairs being a local-time/UTC "
        "difference (most pairs show no such offset).\n"
        "- Driver identity beyond the literal directory letter.\n"
    )
    add("\n### Unknown / unverified\n")
    add(
        "- **Which country or road type any individual session was recorded in.**\n"
        "- **The meaning of the category abbreviations** (`Vta`, `Vtb`, `Vw`, `Vf`, `M`, "
        "`S`, `Y`).\n"
        "- **The cause of any GNSS gap** — no outage is documented anywhere.\n"
        "- Whether any session was deliberately recorded with an induced GNSS outage.\n"
        "- The timezone of either clock (inferred, never stated).\n"
        "- Sensor calibration state, mounting orientation, and phone model.\n"
        "- Whether missing files should exist — no upstream manifest is published.\n"
    )

    # 19 --------------------------------------------------------------
    add("\n## 19. Implications for Phase 2\n")
    add(
        "0. **Split on content, never on file path.** 235-odd files are byte-identical "
        "duplicates of others (§6a); a path-based train/test split leaks data outright.\n"
        "1. **Never assume UTF-8.** Read smartphone CSVs with a cp1252 fallback, or "
        "column lookups will fail on `m/s²` and `Â°`.\n"
        "2. **Strip column names.** Every header field after the first carries a leading "
        "space; match on normalized names, not raw ones.\n"
        '3. **Do not `float()` the satellite column.** Parse `"a / b"` or drop it.\n'
        "4. **Match session ids case-insensitively** (`S-Vta11` ↔ `V-vta11`).\n"
        "5. **Handle two different clocks.** Smartphone elapsed-ms and `DATE`, vehicle "
        "seconds-of-day. The `DATE` millisecond separator is a colon.\n"
        "5a. **Read the measured rate per file.** The smartphone stream includes ~2 Hz, "
        "~24 Hz and ~1000 Hz families alongside the ~10 Hz majority (§9).\n"
        "5b. **Segment discontinuous files.** Some streams concatenate several trips; split "
        "them on the large timestamp jumps instead of integrating straight through.\n"
        "5c. **The smartphone GNSS position is ~0.1 Hz, forward-filled** — not a 10 Hz fix "
        "source (§11).\n"
        "6. **Measure the S↔V offset per pair.** Most pairs are near-aligned, but a minority "
        "are shifted by ~1 h and many show drift; never hardcode an offset.\n"
        "7. **Treat GNSS gaps as observed, not labelled.** If Phase 2 needs outage "
        "scenarios, it must *synthesize* them from continuous data and say so — the "
        "dataset supplies no ground-truth outages.\n"
        "8. **Do not drop 'outlier' rows reflexively.** High accelerations are plausible "
        "vehicle dynamics; see the classifications in `range_findings.csv`.\n"
    )

    # 20 --------------------------------------------------------------
    add("\n## 20. Recommended Phase 2 Data Contract\n")
    add(
        "_Recommendations only — nothing below is implemented in Phase 1._\n\n"
        "**Smartphone signals safe to rely on** (present in every smartphone file "
        "scanned, VERIFIED_FROM_FILE):\n"
        "`GPS LATITUDE`, `GPS LONGITUDE`, `GPS ALTITUDE`, `GPS SPEED`, `GPS ACCURACY`, "
        "`GPS ORIENTATION`, `TIME SINCE START (ms)`, `DATE`, `ACCELEROMETER X/Y/Z`, "
        "`GRAVITY X/Y/Z`, `GYROSCOPE Yaw/Pitch/Roll`, `MAGNETIC FIELD X/Y/Z`, "
        "`ORIENTATION Yaw/Pitch/Roll`.\n\n"
        "**Vehicle/reference signals safe to rely on:**\n"
        "`Time Since Start of Day`, `Latitude`, `Longitude`, `Velocity`, `Heading`, "
        "`Height`, `Vertical velocity`, `Sample period`, `Steering Angle`, "
        "`Wheel Speed FL/FR/RL/RR`, `Yaw Rate`, `Indicated Vehicle Speed`, "
        "`Indicated Longitudinal/Lateral Acceleration`, plus powertrain/chassis channels "
        "(`Gear`, `Engine Speed`, `Brake Pressure`, `Handbrake`, `Clutch Position`, "
        "`Accelerator Pedal Position`, `Battery Voltage`, `Coolant/Air Temperature`).\n\n"
        "**Verified timestamps:** elapsed-time and seconds-of-day columns. The vehicle stream "
        "is uniformly ~10 Hz; the smartphone stream is ~10 Hz for the large majority of files "
        "but not all (§9) — read the rate per file.\n\n"
        f"**Reliable synchronized pairs:** the {len(paired)} paired sessions, subject to "
        "per-pair offset measurement (see `synchronization_report.csv`); prefer pairs "
        "classified `constant_offset` with near-zero drift, and treat "
        "`variable_offset_possible_drift` pairs as needing time-varying alignment.\n\n"
        "**Known GNSS outage information:** none. There is **no loss of fix anywhere in the "
        "dataset and no documented outage ground truth**. `gnss_outages.csv` contains only "
        "observed *position-hold* (staleness) intervals. Any outage scenario Phase 2 needs "
        "must be synthesized and labelled as synthetic.\n\n"
        "**Fields NOT safe to assume:**\n"
        "- a numeric satellite count on the smartphone stream;\n"
        "- UTF-8 encoding;\n"
        "- a timezone-qualified absolute timestamp;\n"
        "- country, road type, or scenario semantics;\n"
        "- that an S/V pair is sample-aligned without checking;\n"
        "- that any gap in GNSS was an intentional/annotated outage.\n"
    )

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("".join(lines), encoding="utf-8")
    return output
